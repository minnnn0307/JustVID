"""Regenerate all JustVID brand assets with Python + Pillow.

One subtly rounded play mark drives WPF geometry, SVG, ICO, and installer art.
The green triangle retains the existing icon's dimensions and placement.
"""
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'JustVID' / 'Assets'
GREEN = '#32C777'
PATH = 'M0,6.8 Q0,0 5.9,3.4 L80.7,46.6 Q86.6,50 80.7,53.4 L5.9,96.6 Q0,100 0,93.2 Z'

# Sample the same quadratic curves used by WPF/SVG for supersampled raster art.
points = [(0, 6.8)]
def line(x, y):
    points.append((x, y))
def quadratic(cx, cy, x, y):
    ax, ay = points[-1]
    for i in range(1, 65):
        t = i / 64
        points.append(((1-t)**2*ax + 2*(1-t)*t*cx + t*t*x,
                       (1-t)**2*ay + 2*(1-t)*t*cy + t*t*y))
quadratic(0, 0, 5.9, 3.4)
line(80.7, 46.6)
quadratic(86.6, 50, 80.7, 53.4)
line(5.9, 96.6)
quadratic(0, 100, 0, 93.2)

ASSETS.mkdir(parents=True, exist_ok=True)
(ASSETS / 'Brand.xaml').write_text(f'''<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
 <!-- Generated by tools/generate_brand.py. All in-app play marks share this geometry. -->
 <SolidColorBrush x:Key="BrandGreen" Color="{GREEN}" />
 <Geometry x:Key="PlayMarkGeometry">{PATH}</Geometry>
</ResourceDictionary>
''', encoding='utf-8')
(ASSETS / 'PlayMark.svg').write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 86.6 100"><path fill="{GREEN}" d="{PATH}"/></svg>
''', encoding='utf-8')
(ASSETS / 'JustVID.svg').write_text(f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256">
 <rect x="8" y="8" width="240" height="240" rx="56" fill="#183B2B"/>
 <path fill="{GREEN}" d="{PATH}" transform="translate(99 64) scale({96/86.6:.10f} 1.28)"/>
</svg>
''', encoding='utf-8')
scale = 4
icon = Image.new('RGBA', (256*scale, 256*scale), (0, 0, 0, 0))
draw = ImageDraw.Draw(icon)
draw.rounded_rectangle((8*scale,8*scale,248*scale,248*scale), radius=56*scale, fill='#183B2B')
draw.polygon([((99+x*96/86.6)*scale, (64+y*1.28)*scale) for x,y in points], fill=GREEN)
icon = icon.resize((256,256), Image.Resampling.LANCZOS)
icon.save(ASSETS / 'JustVID.ico', sizes=[(16,16),(24,24),(32,32),(48,48),(64,64),(128,128),(256,256)])
for name, size, mark_size, center in [
    ('WizardBanner.bmp',(164,314),96,(82,126)),
    ('WizardSmall.bmp',(55,55),48,(27,27))
]:
    canvas = Image.new('RGB', size, '#F3F6F4')
    mark = icon.resize((mark_size,mark_size), Image.Resampling.LANCZOS)
    canvas.paste(mark, (center[0]-mark_size//2, center[1]-mark_size//2), mark)
    canvas.save(ASSETS / name)
